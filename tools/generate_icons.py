#!/usr/bin/env python3
"""Turns icon fonts into QFontIcon's icon data file: every glyph's outline.

The data file lists all icons of the fonts. Applications then pick the ones
they use (qfonticon_embed_icons() in CMake), which are compiled in: no font
file is loaded at run time, so Windows' "Block untrusted fonts" policy, or
anything else that stops fonts from loading, can't break the icons.

Usage (needs fontTools: pip install fonttools):

    python3 tools/generate_icons.py --out icons/fontawesome5.icons \\
        solid=fonts/fa-solid-900.ttf regular=fonts/fa-regular-400.ttf brands=fonts/fa-brands-400.ttf

Each argument is <style>=<font file>. The style names the icon set in icon
lists (e.g. "regular:f15b"); the first one is the default.

Output, one line per entry, fields separated by '|':
    font|<style>|<family>|<font style>|<units per em>|<ascent>|<descent>
    glyph|<style>|<code, hex>|<name>|<advance>|<SVG path, font units, y up>
"""

import argparse
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont


def name_record(font, name_id):
    """A name table entry (family, style, ...), preferring the English one."""
    record = font["name"].getName(name_id, 3, 1, 0x409) or font["name"].getName(name_id, 1, 0, 0)
    return str(record) if record else ""


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", required=True, help="the icon data file to write")
    parser.add_argument("fonts", nargs="+", metavar="STYLE=FONT", help="icon set name and font file")
    args = parser.parse_args()

    lines = ["# QFontIcon icon data: every glyph of the fonts below as an outline.",
             "# Generated by tools/generate_icons.py; do not edit.",
             "# font|style|family|font style|units per em|ascent|descent",
             "# glyph|style|code|name|advance|SVG path (font units, y up)"]
    for entry in args.fonts:
        style, _, path = entry.partition("=")
        if not style or not path:
            sys.exit(f"expected STYLE=FONT, got {entry!r}")
        font = TTFont(path)
        family = name_record(font, 16) or name_record(font, 1)     # typographic family first
        font_style = name_record(font, 17) or name_record(font, 2)
        lines.append("|".join(["font", style, family, font_style, str(font["head"].unitsPerEm),
                               str(font["hhea"].ascent), str(font["hhea"].descent)]))
        glyphs = font.getGlyphSet()
        count = 0
        for code, glyph_name in sorted(font.getBestCmap().items()):
            if code < 0xE000:                       # only the icons (Private Use Area), not spaces etc.
                continue
            pen = SVGPathPen(glyphs, ntos=lambda v: str(round(v)))
            glyphs[glyph_name].draw(pen)
            outline = pen.getCommands()
            if not outline:
                continue
            lines.append("|".join(["glyph", style, f"{code:04x}", glyph_name,
                                   str(glyphs[glyph_name].width), outline]))
            count += 1
        print(f"{style}: {count} icons from {path} ({family} {font_style})")
    with open(args.out, "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
